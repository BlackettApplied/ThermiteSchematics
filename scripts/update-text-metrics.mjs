import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { deflateRawSync } from "node:zlib";
import { openSync } from "fontkit";
import { format } from "prettier";

// Generate the conservative per-glyph envelope. Exact printable metrics separately
// parse the bundled, feature-free faces; browser-only faces never ship.
const inputs = [
  ...[
    "NotoSans-Regular",
    "NotoSans-Bold",
    "NotoSansMath-Regular",
    "NotoSansMono-Regular",
  ].map((name) => [
    `packages/${name === "NotoSansMono-Regular" ? "cli" : "render"}/assets/fonts/${name}.ttf`,
    true,
  ]),
  ...["Regular", "Bold"].map((weight) => [
    `node_modules/pdfjs-dist/standard_fonts/LiberationSans-${weight}.ttf`,
    false,
  ]),
  ...[
    "DejaVuSans",
    "DejaVuSans-Bold",
    "DejaVuSansMono",
    "DejaVuSansMono-Bold",
  ].map((name) => [`node_modules/dejavu-fonts-ttf/ttf/${name}.ttf`, false]),
];
const fonts = inputs.map(([source, embedded]) => {
  const path = fileURLToPath(new URL(`../${source}`, import.meta.url)),
    font = openSync(path);
  if (!("unitsPerEm" in font))
    throw Error(`Expected a single TrueType font: ${source}`);
  return { source, embedded, path, font };
});
const sources = await Promise.all(
  fonts.map(async ({ source, path }) => ({
    source,
    sha256: createHash("sha256")
      .update(await readFile(path))
      .digest("hex"),
  })),
);
const codes = [...new Set(fonts.flatMap(({ font }) => font.characterSet))]
  .filter((code) => fonts.some(({ font }) => font.hasGlyphForCodePoint(code)))
  .sort((a, b) => a - b);
const bytes = [];
function integer(value) {
  if (!Number.isSafeInteger(value) || value < 0)
    throw Error(`Invalid metric integer: ${value}`);
  do {
    const byte = value % 128;
    value = Math.floor(value / 128);
    bytes.push(byte | (value ? 128 : 0));
  } while (value);
}
let previous = 0;
for (const code of codes) {
  let envelope = 0,
    ascent = 0,
    descent = 0,
    coverage = 0;
  for (const [index, { font, embedded }] of fonts.entries()) {
    if (!font.hasGlyphForCodePoint(code)) continue;
    const glyph = font.glyphForCodePoint(code),
      scale = 10000 / font.unitsPerEm,
      box = glyph.bbox,
      ink = Number.isFinite(box.minX) ? box.maxX - box.minX : 0,
      // Retain the initial Noto reserve; measured browser faces bound themselves.
      reserve = embedded ? 1.1 : 1;
    envelope = Math.max(
      envelope,
      Math.ceil(Math.max(glyph.advanceWidth, ink) * scale * reserve),
    );
    ascent = Math.max(
      ascent,
      Math.ceil(Math.max(0, box.maxY || 0) * scale * reserve),
    );
    descent = Math.max(
      descent,
      Math.ceil(Math.max(0, -box.minY || 0) * scale * reserve),
    );
    // svg-to-pdfkit cannot paint zero-advance glyphs. Only embedded faces count.
    if (embedded && glyph.advanceWidth > 0) coverage |= 1 << index;
  }
  for (const value of [code - previous, envelope, ascent, descent, coverage])
    integer(value);
  previous = code;
}
const packed = deflateRawSync(Buffer.from(bytes), { level: 9 }).toString(
  "base64",
);
const output = await format(
  `// Generated by scripts/update-text-metrics.mjs; do not edit.\n// Deflated unsigned varints: delta code point, envelope, ascent, descent (1/10000 em), drawable embedded-face mask.\nexport const metricSources: readonly { source: string; sha256: string }[] = ${JSON.stringify(sources)};\nexport const glyphCount: number = ${codes.length};\nexport const packedGlyphMetrics: string = ${JSON.stringify(packed)};\n`,
  { parser: "typescript" },
);
const destination = new URL(
  "../packages/render/src/text-metrics-data.ts",
  import.meta.url,
);
if (process.argv.slice(2).join(" ") === "--write")
  await writeFile(destination, output);
else if (process.argv.slice(2).join(" ") === "--check") {
  if ((await readFile(destination, "utf8")) !== output)
    throw Error(
      "Stale text metrics. Run bun scripts/update-text-metrics.mjs --write.",
    );
} else throw Error("Use --write or --check");
console.log(
  `Text metrics ${process.argv[2]}: ${codes.length} glyphs, ${sources.length} fonts; ${Buffer.byteLength(output)} source bytes.`,
);
